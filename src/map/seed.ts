export function blankScenario(name: string, from?: Scenario): Scenario {
  const center = from?.center ?? ([-80.409, 37.13] as Scenario["center"]);
  const zoom = from?.zoom ?? 12;
  return {
    id: `sc-${Math.random().toString(36).slice(2, 8)}`,
    name,
    center,
    zoom,
    home: { center: [...center] as Scenario["center"], zoom },
    basemap: from?.basemap ?? "dark",
    showLabels: false,
    showGrid: false,
    showRelief: false,
    showLinks: false,
    iconSize: from?.iconSize ?? "m",
    mode: from?.mode ?? "edit",
    groups: defaultGroups(),
    factions: DEFAULT_FACTIONS.map((faction) => ({ ...faction })),
    levels: DEFAULT_LEVELS.map((level) => ({ ...level })),
    features: [],
    moments: [{ id: "start", name: "起始", features: [] }],
    activeMomentId: "start",
    compareIds: [],
    updatedAt: Date.now(),
  };
}
